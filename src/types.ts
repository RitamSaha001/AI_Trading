export const ASSETS = ['BTC','ETH','SOL','ADA'] as const;
export type Asset = typeof ASSETS[number];
export type Side='buy'|'sell';
export type Timeframe='1H'|'1D'|'1W'|'1M';
export type Candle={time:number;open:number;high:number;low:number;close:number;volume:number};
export type Market={asset:Asset;name:string;price:number;change24h:number;high24h:number;low24h:number;volume24h:number;history:number[];candles:Candle[];source:'Binance'|'Coinbase'};
export type Order={id:string;ts:number;side:Side;asset:Asset;amount:number;price:number;fee:number;notional:number;auto:boolean;status:'filled'};
export type AlertRule={id:string;asset:Asset;type:'above'|'below'|'changeUp'|'changeDown';value:number;enabled:boolean;triggered:boolean};
export type Strategy={asset:Asset;enabled:boolean;maxAllocation:number;cooldownSec:number};
export type Settings={geminiApiKey:string;geminiModel:string};
export type AppState={cash:number;initialCash:number;positions:Record<Asset,number>;watchlist:Asset[];orders:Order[];alerts:AlertRule[];strategies:Strategy[];settings:Settings;notifications:{id:string;ts:number;title:string;body:string}[];timeframe:Timeframe;selectedAsset:Asset};
